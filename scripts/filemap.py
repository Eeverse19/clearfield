"""Regenerate the file map inside INDEX.md (navigation, not content).

Usage: python scripts/filemap.py [--check]

Walks the repo (excluding .git, virtualenvs, data/, caches) and rewrites
the section between <!-- FILEMAP:START --> and <!-- FILEMAP:END --> in
INDEX.md with one line per file: path, size, and the first docstring
line (Python) or first heading (Markdown). The hand-written part of
INDEX.md (start-here routes) is never touched. --check exits 1 if the
committed map is stale, without writing. Stdlib only.
"""

import ast
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
INDEX = REPO_ROOT / "INDEX.md"
START, END = "<!-- FILEMAP:START -->", "<!-- FILEMAP:END -->"
EXCLUDE_DIRS = {".git", ".venv", ".venv-sam", ".pytest_cache", "__pycache__",
                "data", "node_modules", ".agents", ".opencode"}
EXCLUDE_SUFFIXES = {".pyc", ".db", ".sqlite3"}


def summarize(path: Path) -> str:
    try:
        text = path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return ""
    if path.suffix == ".py":
        try:
            doc = ast.get_docstring(ast.parse(text)) or ""
            return doc.strip().splitlines()[0].strip() if doc.strip() else ""
        except SyntaxError:
            return ""
    if path.suffix == ".md":
        for line in text.splitlines():
            if line.startswith("#"):
                return line.lstrip("# ").strip()
        return ""
    return ""


def collect(root: Path) -> list[tuple[str, int, str]]:
    out = []
    for path in sorted(root.rglob("*")):
        if not path.is_file():
            continue
        rel = path.relative_to(root)
        if any(part in EXCLUDE_DIRS for part in rel.parts):
            continue
        if path.suffix in EXCLUDE_SUFFIXES or path.name in ("uv.lock", "INDEX.md"):
            continue  # INDEX.md would list its own size and never be stable
        out.append((rel.as_posix(), path.stat().st_size, summarize(path)))
    return out


def render(files: list[tuple[str, int, str]]) -> str:
    lines = [f"_{len(files)} files (generated by `scripts/filemap.py`; "
             "data/, venvs and caches excluded)._", ""]
    group = None
    for rel, size, summary in files:
        top = rel.split("/")[0] if "/" in rel else "(root)"
        if top != group:
            group = top
            lines += [f"### {group}", ""]
        kb = f"{size / 1024:.0f} KB" if size >= 1024 else f"{size} B"
        lines.append(f"- `{rel}` ({kb})" + (f" — {summary}" if summary else ""))
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    body = render(collect(REPO_ROOT))
    if not INDEX.exists():
        print("INDEX.md missing; create it with the FILEMAP markers first",
              file=sys.stderr)
        return 1
    text = INDEX.read_text(encoding="utf-8")
    if START not in text or END not in text:
        print(f"INDEX.md lacks {START} / {END} markers", file=sys.stderr)
        return 1
    head, rest = text.split(START, 1)
    _, tail = rest.split(END, 1)
    new = f"{head}{START}\n\n{body}\n{END}{tail}"
    if "--check" in argv:
        if new != text:
            print("INDEX.md file map is stale; run scripts/filemap.py", file=sys.stderr)
            return 1
        print("INDEX.md file map is current")
        return 0
    INDEX.write_text(new, encoding="utf-8")
    print(f"INDEX.md updated ({body.count(chr(10))} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
